#!/usr/bin/env bash
# Deploy the whole stack on this server, from source, and prove it answers.
#
# Run on the server, from the repository root, as the deploy user:
#
#   cd ~/MoraPay && git pull && infra/scripts/server-deploy.sh
#
# Safe to run repeatedly. It rebuilds, restarts, and re-checks; it does not
# touch the database beyond running migrations, so transfer history and the
# ledger survive a redeploy.
#
# On first run it writes .env with generated secrets. Those secrets are for a
# demonstration against simulated rails. Real ones come from a vault before
# anything approaching live funds (BUILD_PLAN 12.5, OPEN_ITEMS P3).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"

COMPOSE="docker compose -f infra/compose/server.yml"
WEB_PORT="${WEB_PUBLIC_PORT:-80}"
ADMIN_PORT="${ADMIN_PUBLIC_PORT:-8080}"

# ---------------------------------------------------------------------- TLS
#
# Opt in with TLS=1. Without a domain, sslip.io resolves any IP-shaped name to
# that IP — including a prefixed one — so the two names needed here already
# point at this server and Let's Encrypt can validate them over HTTP-01.
#
# This is worth doing before anyone is shown the application. Over plain HTTP
# the browser will not register a service worker at all, so the PWA cannot
# install and the offline shell cannot be tested — and passwords cross the
# network in the clear.
TLS="${TLS:-0}"
if [ "$TLS" = "1" ]; then
  PUBLIC_HOSTNAME="${PUBLIC_HOSTNAME:-}"
  ADMIN_HOSTNAME="${ADMIN_HOSTNAME:-}"
  # Filled in below, once the address is known.
  COMPOSE="$COMPOSE --profile tls"
  # The front ends move off the public interface; Caddy is the only listener.
  export WEB_BIND=127.0.0.1 ADMIN_BIND=127.0.0.1
  WEB_PORT=3000
  ADMIN_PORT=3001
fi

# The address the browser will use. Detected, because the whole point of this
# file is that there is no domain yet; override when there is one, or when the
# server is behind NAT and its own view of its address is wrong.
PUBLIC_HOST="${PUBLIC_HOST:-$(curl -fsS --max-time 5 https://api.ipify.org 2>/dev/null || hostname -I | awk '{print $1}')}"
if [ -z "$PUBLIC_HOST" ]; then
  echo "✗ Could not determine this server's public address. Set PUBLIC_HOST=<ip> and re-run." >&2
  exit 1
fi

# ------------------------------------------------------------------ secrets
if [ ! -f .env ]; then
  echo "→ first run: generating .env"
  command -v openssl >/dev/null 2>&1 || { echo "✗ openssl is required" >&2; exit 1; }
  gen() { openssl rand -base64 32 | tr -d '\n=+/' | cut -c1-40; }

  cp .env.example .env
  {
    echo ""
    echo "# ---- generated by server-deploy.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "POSTGRES_PASSWORD=$(gen)"
    echo "JWT_ACCESS_SECRET=$(gen)"
    echo "ADMIN_JWT_ACCESS_SECRET=$(gen)"
    echo "QUOTE_SIGNING_SECRET=$(gen)"
    echo "FIELD_ENCRYPTION_KEY=$(openssl rand -base64 32)"
    echo "TOKENISATION_SALT=$(gen)"
    echo "PROVIDER_SIGNING_SECRET_PAYIN_RU_SIM=$(gen)"
    echo "PROVIDER_SIGNING_SECRET_PAYOUT_NG_SIM=$(gen)"
    echo "PROVIDER_SIGNING_SECRET_PAYOUT_GH_SIM=$(gen)"
    echo "PROVIDER_SIGNING_SECRET_PAYIN_NG_SIM=$(gen)"
    echo "PROVIDER_SIGNING_SECRET_PAYIN_GH_SIM=$(gen)"
    echo "PROVIDER_SIGNING_SECRET_PAYIN_CM_SIM=$(gen)"
    echo "PROVIDER_SIGNING_SECRET_PAYIN_BJ_SIM=$(gen)"
    echo "PROVIDER_SIGNING_SECRET_PAYOUT_ZA_SIM=$(gen)"
    echo "PROVIDER_SIGNING_SECRET_PAYOUT_CM_SIM=$(gen)"
    echo "PROVIDER_SIGNING_SECRET_PAYOUT_BJ_SIM=$(gen)"
    echo "NODE_ENV=production"
    echo "LIVE_FUNDS_ENABLED=false"
    echo ""
    echo "# This is a demonstration server, so the seeded staff and sender"
    echo "# accounts — whose passwords are published in docs/DEMO.md — are"
    echo "# wanted here despite NODE_ENV=production. Saying so explicitly is"
    echo "# what lets the seed run; the seed refuses outright if"
    echo "# LIVE_FUNDS_ENABLED is ever true, and that has no override."
    echo "#"
    echo "# Delete this line before this database is used for anything real."
    echo "ALLOW_DEMONSTRATION_SEED=true"
  } >> .env
  chmod 600 .env
  echo "   .env written, mode 600. It is gitignored; keep it that way."
fi

# The two origins are derived every run, so moving to a domain is one variable.
if [ "$TLS" = "1" ]; then
  # The Caddyfile's global `email` line has no value without this, which Caddy
  # rejects, so the certificate never arrives. Given once, remembered in .env.
  ACME_EMAIL="${ACME_EMAIL:-$(grep -E '^ACME_EMAIL=' .env | tail -1 | cut -d= -f2- || true)}"
  if [ -z "$ACME_EMAIL" ]; then
    echo "✗ TLS=1 needs an address for certificate notices, once:" >&2
    echo "    ACME_EMAIL=you@example.com TLS=1 infra/scripts/server-deploy.sh" >&2
    exit 1
  fi
  grep -qE '^ACME_EMAIL=' .env || printf '\nACME_EMAIL=%s\n' "$ACME_EMAIL" >> .env
  # Default to sslip.io names for this server's address. Override both when a
  # real domain exists — nothing else in the deployment needs to change.
  PUBLIC_HOSTNAME="${PUBLIC_HOSTNAME:-${PUBLIC_HOST}.sslip.io}"
  ADMIN_HOSTNAME="${ADMIN_HOSTNAME:-admin.${PUBLIC_HOST}.sslip.io}"
  PUBLIC_ORIGIN="${PUBLIC_ORIGIN:-https://${PUBLIC_HOSTNAME}}"
  ADMIN_ORIGIN="${ADMIN_ORIGIN:-https://${ADMIN_HOSTNAME}}"
  export PUBLIC_HOSTNAME ADMIN_HOSTNAME ACME_EMAIL="${ACME_EMAIL:-}" \
    CADDY_ACME_CA="${CADDY_ACME_CA:-https://acme-v02.api.letsencrypt.org/directory}"
else
  PUBLIC_ORIGIN="${PUBLIC_ORIGIN:-http://${PUBLIC_HOST}$([ "$WEB_PORT" = "80" ] || echo ":$WEB_PORT")}"
  ADMIN_ORIGIN="${ADMIN_ORIGIN:-http://${PUBLIC_HOST}:${ADMIN_PORT}}"
fi
export PUBLIC_ORIGIN ADMIN_ORIGIN WEB_PUBLIC_PORT="$WEB_PORT" ADMIN_PUBLIC_PORT="$ADMIN_PORT"
# shellcheck disable=SC2046
export POSTGRES_PASSWORD="$(grep -E '^POSTGRES_PASSWORD=' .env | cut -d= -f2-)"

# -------------------------------------------------------------------- eipay
#
# Opt in with EIPAY=1 (and TLS=1). Runs the developers' eipay app as its own
# service next to MoraPay, for integration testing. docs/EIPAY_INTEGRATION.md
# is the runbook; this block only refuses the unsafe ways of doing it.
#
#   TLS=1 EIPAY=1 infra/scripts/server-deploy.sh
#
# The optional-sites directory is rewritten every run, so a run without EIPAY=1
# takes eipay off the public address again.
rm -rf .caddy-sites && mkdir -p .caddy-sites
EIPAY="${EIPAY:-0}"
if [ "$EIPAY" = "1" ]; then
  [ "$TLS" = "1" ] || {
    echo "✗ EIPAY=1 needs TLS=1: wallet sign-in does not work over plain HTTP." >&2; exit 1; }

  EIPAY_SRC="${EIPAY_SRC:-$(cd "$ROOT/.." && pwd)/eipay}"
  EIPAY_ENV_FILE="${EIPAY_ENV_FILE:-$(cd "$ROOT/.." && pwd)/eipay.env}"
  EIPAY_HOSTNAME="${EIPAY_HOSTNAME:-eipay.${PUBLIC_HOST}.sslip.io}"

  [ -d "$EIPAY_SRC/.git" ] || {
    echo "✗ no eipay checkout at $EIPAY_SRC" >&2
    echo "  git clone <eipay repository> $EIPAY_SRC" >&2; exit 1; }
  # A live .env inside the checkout is how the keys leaked the first time, and
  # the image build would copy it into a layer.
  if find "$EIPAY_SRC" -maxdepth 1 -name '.env*' ! -name '.env.example' | grep -q .; then
    echo "✗ $EIPAY_SRC contains an .env file. Move it to $EIPAY_ENV_FILE and delete it there." >&2; exit 1
  fi
  [ -f "$EIPAY_ENV_FILE" ] || {
    echo "✗ $EIPAY_ENV_FILE is missing. Start from $EIPAY_SRC/.env.example, with NEW keys." >&2; exit 1; }
  case "$(cd "$(dirname "$EIPAY_ENV_FILE")" && pwd)/" in
    "$ROOT"/*|"$EIPAY_SRC"/*)
      echo "✗ $EIPAY_ENV_FILE must live outside both repositories." >&2; exit 1 ;;
  esac
  [ "$(stat -c %a "$EIPAY_ENV_FILE")" = "600" ] || {
    echo "✗ $EIPAY_ENV_FILE must be mode 600: chmod 600 $EIPAY_ENV_FILE" >&2; exit 1; }

  # Windows line endings from Notepad would end up inside every value.
  sed -i 's/\r$//' "$EIPAY_ENV_FILE"
  # Always succeeds: under `set -e -o pipefail` a key that is absent (grep finds
  # nothing) would otherwise end the whole script silently at the first
  # `v="$(eipay_val ...)"`, before any message could say which key.
  eipay_val() {
    { grep -E "^$1=" "$EIPAY_ENV_FILE" | tail -1 | cut -d= -f2- \
        | sed -e 's/^["'\'']//' -e 's/["'\'']$//'; } || true
  }
  # Replaces every line for $1 with one line, so the file never holds two
  # values for a key and the reader never has to guess which one wins.
  eipay_set() { sed -i "/^$1=/d" "$EIPAY_ENV_FILE"; printf '%s=%s\n' "$1" "$2" >> "$EIPAY_ENV_FILE"; }

  # Values derived from this deployment, written here so nobody types them.
  # They follow EIPAY_HOSTNAME, so moving to a real domain updates all of them.
  eipay_set APP_URL "https://${EIPAY_HOSTNAME}"
  eipay_set NEXT_PUBLIC_APP_URL "https://${EIPAY_HOSTNAME}"
  eipay_set SMILE_ID_CALLBACK_URL "https://${EIPAY_HOSTNAME}/api/kyc/smile-id/callback"
  privy_id="$(eipay_val NEXT_PUBLIC_PRIVY_APP_ID)"
  if [ -n "$privy_id" ]; then
    eipay_set PRIVY_JWKS_URL "https://auth.privy.io/api/v1/apps/${privy_id}/jwks.json"
    [ -n "$(eipay_val PRIVY_ISSUER)" ] || eipay_set PRIVY_ISSUER privy.io
  fi
  [ -n "$(eipay_val PAYCREST_BASE_API_URL)" ] || eipay_set PAYCREST_BASE_API_URL https://api.paycrest.io/v1

  # Secrets that belong to this deployment alone, generated once. Rotating
  # ENCRYPTION_KEY later makes saved recipients unreadable (their runbook has
  # the re-encryption step), so it is never regenerated once present.
  for k in INTERNAL_API_KEY ENCRYPTION_KEY INJECTED_SESSION_SECRET; do
    if [ -z "$(eipay_val "$k")" ]; then
      eipay_set "$k" "$(openssl rand -hex 32)"
      echo "  generated $k in $EIPAY_ENV_FILE"
    fi
  done

  missing=""
  for k in NEXT_PUBLIC_PRIVY_APP_ID PRIVY_APP_SECRET SUPABASE_URL SUPABASE_SECRET_KEY \
           PAYCREST_SENDER_KEY NEXT_PUBLIC_STARKNET_RPC_URL NEXT_PUBLIC_GUEST_REFUND_ADDRESS; do
    v="$(eipay_val "$k")"
    case "$v" in ""|*your*|*YOUR*|*PLACEHOLDER*|*"<"*|"0x...") missing="$missing $k" ;; esac
  done
  [ -z "$missing" ] || { echo "✗ $EIPAY_ENV_FILE has no real value for:$missing" >&2; exit 1; }
  # Without this, eipay refunds failed guest orders to an address hard-coded in
  # its source, which belongs to nobody we can name.
  if [ "$(eipay_val NEXT_PUBLIC_GUEST_REFUND_ADDRESS | tr 'A-F' 'a-f')" = "0x2b4fb6f7255def56d985fb01134ab1431efbd3be" ]; then
    echo "✗ NEXT_PUBLIC_GUEST_REFUND_ADDRESS is eipay's built-in default. Set the Company's own wallet address." >&2; exit 1
  fi
  # The nTZS webhook skips its signature check when this is unset. It is behind
  # the testers' gate today; this keeps it safe if that ever changes.
  if [ -n "$(eipay_val NTZS_API_KEY)" ] && [ -z "$(eipay_val NTZS_WEBHOOK_SECRET)" ]; then
    echo "✗ NTZS_API_KEY is set without NTZS_WEBHOOK_SECRET: the webhook would accept unsigned calls." >&2; exit 1
  fi
  echo "  eipay address https://${EIPAY_HOSTNAME} (add it to Privy's allowed domains)"

  # The testers' gate. One shared login, generated once, kept in MoraPay's .env
  # as a bcrypt hash; the password itself is printed once and never stored.
  if ! grep -qE '^EIPAY_TEST_PASSWORD_HASH=' .env; then
    command -v openssl >/dev/null 2>&1 || { echo "✗ openssl is required" >&2; exit 1; }
    # Read off the console screen by eye (it cannot copy), so no characters that
    # look alike — 0/O, 1/l/I, 5/S, 2/Z, 8/B — and in groups of five.
    EIPAY_TEST_PASSWORD="$(openssl rand -base64 96 | tr -dc 'abcdefghjkmnpqrstuvwxyzACDEFGHJKLMNPQRTUVWXY34679' \
      | cut -c1-20 | sed -E 's/(.{5})(.{5})(.{5})(.{5})/\1-\2-\3-\4/')"
    hash="$(docker run --rm caddy:2-alpine caddy hash-password --plaintext "$EIPAY_TEST_PASSWORD")"
    { echo ""; echo "# eipay testers' gate (server-deploy.sh). Remove both lines to issue a new password."
      echo "EIPAY_TEST_USER=tester"
      echo "EIPAY_TEST_PASSWORD_HASH='${hash}'"; } >> .env
  fi
  EIPAY_TEST_USER="$(grep -E '^EIPAY_TEST_USER=' .env | tail -1 | cut -d= -f2- || true)"
  EIPAY_TEST_PASSWORD_HASH="$(grep -E '^EIPAY_TEST_PASSWORD_HASH=' .env | tail -1 | cut -d= -f2- | sed -e "s/^'//" -e "s/'$//" || true)"
  if [ -z "$EIPAY_TEST_USER" ] || [ -z "$EIPAY_TEST_PASSWORD_HASH" ]; then
    echo "✗ the testers' login in .env is incomplete. Delete both EIPAY_TEST_* lines and re-run." >&2; exit 1
  fi
  export EIPAY_HOSTNAME EIPAY_ENV_FILE EIPAY_TEST_USER EIPAY_TEST_PASSWORD_HASH

  cp infra/caddy/eipay.caddy .caddy-sites/
  COMPOSE="$COMPOSE --profile eipay"

  echo "→ building eipay from $EIPAY_SRC ($(git -C "$EIPAY_SRC" rev-parse --short HEAD))"
  DOCKER_BUILDKIT=1 docker build -f infra/docker/eipay.Dockerfile \
    --secret id=eipay_env,src="$EIPAY_ENV_FILE" \
    -t morapay-eipay:local "$EIPAY_SRC"
fi

echo "→ building (a few minutes on the first run; layers are cached after that)"
$COMPOSE build

echo "→ migrating and seeding"
$COMPOSE run --rm migrate

echo "→ starting"
$COMPOSE up -d --remove-orphans

# --------------------------------------------------------------- verifying
wait_for() {
  local url="$1" want="${2:-200}" tries="${3:-90}"
  for _ in $(seq "$tries"); do
    [ "$(curl -s -o /dev/null -m 5 -w '%{http_code}' "$url" || echo 000)" = "$want" ] && return 0
    sleep 2
  done
  return 1
}

echo "→ verifying"
wait_for "http://localhost:${WEB_PORT}/login" || {
  echo "✗ the sender app did not come up" >&2; $COMPOSE logs --tail=30 web >&2; exit 1; }
wait_for "http://localhost:${ADMIN_PORT}/login" || {
  echo "✗ the back office did not come up" >&2; $COMPOSE logs --tail=30 admin >&2; exit 1; }

# The check that matters on a server with no domain: the front end must be able
# to reach the API through its own origin. If this fails the pages still render
# and every action fails, which is the confusing failure this whole arrangement
# exists to prevent.
#
# It retries, because the front ends answer well before the API finishes
# booting — Nest maps every route and connects to PostgreSQL first, which takes
# a few seconds longer than serving a login page. Asking once, immediately
# after the front ends come up, reports a healthy stack as broken.
wait_for_body() {
  local url="$1" needle="$2" tries="${3:-60}"
  for _ in $(seq "$tries"); do
    curl -s -m 5 "$url" 2>/dev/null | grep -q "$needle" && return 0
    sleep 2
  done
  return 1
}

for entry in "sender app:$WEB_PORT" "back office:$ADMIN_PORT"; do
  port="${entry##*:}"
  if wait_for_body "http://localhost:${port}/api/health" '"status"'; then
    echo "✓ ${entry%%:*} reaches the API through its own origin"
  else
    echo "✗ ${entry%%:*} cannot reach the API through /api" >&2
    $COMPOSE logs --tail=30 api >&2
    exit 1
  fi
done

if wait_for_body "http://localhost:${WEB_PORT}/api/health/ledger" '"balanced":true' 30; then
  echo "✓ ledger balanced"
else
  echo "✗ the ledger does not report itself balanced — do not demonstrate this" >&2
  exit 1
fi

if [ "$TLS" = "1" ]; then
  # Caddy fetches certificates on first request to each name, so the first load
  # is slow and can fail while ACME is still working. Wait for the real thing
  # rather than printing a URL that is not ready yet.
  echo "→ waiting for certificates (first issuance takes up to a minute)"
  for name in "$PUBLIC_HOSTNAME" "$ADMIN_HOSTNAME"; do
    ok=0
    for _ in $(seq 45); do
      if curl -sS -o /dev/null -m 8 "https://${name}/login" 2>/dev/null; then ok=1; break; fi
      sleep 2
    done
    if [ "$ok" = "1" ]; then
      echo "✓ https://${name} serving with a trusted certificate"
    else
      echo "✗ https://${name} did not come up." >&2
      echo "  Check that ports 80 and 443 are open in ufw and in the Hetzner" >&2
      echo "  firewall — Let's Encrypt validates over port 80, so a redirect" >&2
      echo "  is not enough, it has to reach Caddy." >&2
      $COMPOSE logs --tail=25 caddy >&2
      exit 1
    fi
  done
fi

if [ "$EIPAY" = "1" ]; then
  echo "→ verifying eipay"
  wait_for "http://localhost:${EIPAY_LOCAL_PORT:-3002}/" 200 90 || {
    echo "✗ eipay did not come up" >&2; $COMPOSE logs --tail=40 eipay >&2; exit 1; }
  echo "✓ eipay answers on the server"
  ok=0
  for _ in $(seq 45); do
    code="$(curl -s -o /dev/null -m 8 -w '%{http_code}' "https://${EIPAY_HOSTNAME}/" 2>/dev/null || echo 000)"
    [ "$code" = "401" ] && { ok=1; break; }
    sleep 2
  done
  if [ "$ok" = "1" ]; then
    echo "✓ https://${EIPAY_HOSTNAME} has a trusted certificate and asks testers to sign in"
  else
    echo "✗ https://${EIPAY_HOSTNAME} did not answer 401 without a login (got ${code})." >&2
    echo "  Either the certificate is not issued yet or the gate is not in place. Not ready." >&2
    $COMPOSE logs --tail=25 caddy >&2
    exit 1
  fi
fi

cat <<EOF

  Sender app     ${PUBLIC_ORIGIN}
  Back office    ${ADMIN_ORIGIN}
  API health     ${PUBLIC_ORIGIN}/api/health

  Sender   chidi@demo.morapay.local / morapay-demo-2026
  Staff    compliance@morapay.local / morapay-local-staff-2026
EOF

if [ "$TLS" = "1" ]; then
  cat <<EOF

  Served over HTTPS with a Let's Encrypt certificate, renewed automatically.
  The app can now be installed to a home screen and the offline shell works.

  The hostname contains the IP, so it changes if the server does — right for a
  demonstration, wrong for a pilot. Point a real domain here and re-run with
  PUBLIC_HOSTNAME and ADMIN_HOSTNAME set; nothing else changes.
EOF
else
  cat <<EOF

  This is plain HTTP. Passwords cross the network in the clear and the browser
  will not install the app to a home screen, because a service worker needs a
  secure context. Acceptable for a demonstration against simulated rails with
  fictional senders; not acceptable for anything else.

  For a real certificate today, without owning a domain:
      TLS=1 infra/scripts/server-deploy.sh
EOF
fi

if [ "$EIPAY" = "1" ]; then
  cat <<EOF

  eipay          https://${EIPAY_HOSTNAME}   (testers only, user: ${EIPAY_TEST_USER})
EOF
  if [ -n "${EIPAY_TEST_PASSWORD:-}" ]; then
    cat <<EOF
  Testers' password, shown this once and not stored anywhere in clear:
                 ${EIPAY_TEST_PASSWORD}
  Give it only to the named testers. To issue a new one, delete the two
  EIPAY_TEST_* lines from .env and re-run.
EOF
  fi
  cat <<EOF
  Integration checks: infra/scripts/eipay-check.sh
EOF
fi

cat <<EOF

  Logs:    $COMPOSE logs -f api
  Stop:    $COMPOSE down
EOF
